a = 3
b = 55

# arithmetic operators
print(a + b)
print(a - b)
print(a * b)
print(a / b)

# assignment operators(=, -=, +=, *=, /=)
c= 4-2
print(c)
p=6
p += 2
print(p)

# comparison operators(==, !=, >, <, >=, <=)
print(a==b)
print(a!=b)
print(a>b)
print(a<b)
print(a>=b)
print(a<=b)


# logical operators(and, or, not)
print(a>2 and b>2)  #tt
print(a>2 or b>2)   #t or f
print(not(a>2 and b>2)) #t-f f-t

